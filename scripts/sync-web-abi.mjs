// Regenerates apps/web/src/lib/chain/generated-abi.ts from the Foundry ABI exports.
// Run after `packages/contracts/script/export-abi.sh`: node scripts/sync-web-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";

const contracts = {
  registryAbi: "ShowmarkRegistry",
  vaultAbi: "CampaignVault",
  bondAbi: "OrganizerBond",
  lensAbi: "PresenceLens",
  stampAbi: "PresenceStamp",
  qieIdCheckAbi: "QieIdCheck",
};

let out = "// Generated by scripts/sync-web-abi.mjs from packages/contracts/abi. Do not edit by hand.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const abi = JSON.parse(readFileSync(new URL(`../packages/contracts/abi/${file}.json`, import.meta.url), "utf8"));
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(new URL("../apps/web/src/lib/chain/generated-abi.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(contracts).length} ABIs`);
