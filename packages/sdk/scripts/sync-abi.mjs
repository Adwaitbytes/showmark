// Regenerates src/abi/{registry,vault,lens}.ts from the Foundry contracts so the SDK never drifts from them.
//
// Source, in order of preference:
//   1. packages/contracts/abi/<Name>.json, exported by the contracts workstream (an ABI array or an artifact).
//   2. A fresh `forge build` of packages/contracts into packages/sdk/.forge-out (never touches contracts/out).
// For each target the first name found wins, so the SDK moves from interface to implementation automatically.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const sdkRoot = fileURLToPath(new URL("../", import.meta.url));
const contractsRoot = fileURLToPath(new URL("../../contracts/", import.meta.url));
const exportedDir = `${contractsRoot}abi/`;
const forgeOut = `${sdkRoot}.forge-out/`;

const targets = [
  { file: "registry.ts", exportName: "registryAbi", names: ["ShowmarkRegistry"] },
  { file: "vault.ts", exportName: "vaultAbi", names: ["CampaignVault", "ICampaignVault"] },
  { file: "lens.ts", exportName: "presenceAbi", names: ["PresenceLens", "IPresence"] },
];

let built = false;
function buildContracts() {
  if (built) return;
  const result = spawnSync(
    "forge",
    ["build", "--root", contractsRoot, "--out", `${forgeOut}out`, "--cache-path", `${forgeOut}cache`, "--skip", "test", "--skip", "script"],
    { stdio: "inherit" },
  );
  if (result.error || result.status !== 0) {
    console.error("forge build failed. Install Foundry (https://getfoundry.sh) or export ABIs to packages/contracts/abi.");
    process.exit(1);
  }
  built = true;
}

function readAbi(name) {
  const exported = `${exportedDir}${name}.json`;
  if (existsSync(exported)) {
    const json = JSON.parse(readFileSync(exported, "utf8"));
    return { abi: Array.isArray(json) ? json : json.abi, source: `packages/contracts/abi/${name}.json` };
  }
  buildContracts();
  const artifact = `${forgeOut}out/${name}.sol/${name}.json`;
  if (!existsSync(artifact)) return null;
  return { abi: JSON.parse(readFileSync(artifact, "utf8")).abi, source: `forge build of packages/contracts (${name}.sol)` };
}

for (const target of targets) {
  let found = null;
  for (const name of target.names) {
    found = readAbi(name);
    if (found) break;
  }
  if (!found || !Array.isArray(found.abi)) {
    console.error(`No ABI found for ${target.names.join(" or ")}`);
    process.exit(1);
  }
  const body = [
    `// Generated by \`pnpm sync-abi\` from ${found.source}. Do not edit by hand.`,
    "",
    `export const ${target.exportName} = ${JSON.stringify(found.abi, null, 2)} as const;`,
    "",
  ].join("\n");
  writeFileSync(`${sdkRoot}src/abi/${target.file}`, body);
  console.log(`src/abi/${target.file} <- ${found.source} (${found.abi.length} entries)`);
}
